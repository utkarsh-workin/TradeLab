def normalize_name(text):
    """
    Convert filename/asset name into a comparable format.
    Example:
        'GACM-Technologies_clean.csv'
        'GACM Technologies'
    both become similar normalized strings.
    """
    text = str(text).lower()

    for char in [
        "-", "_", " ", ".", "(", ")", "[", "]"
    ]:
        text = text.replace(char, "")

    return text


def find_processed_file(asset):
    """
    Automatically locate processed CSV for an asset.
    """

    csv_files = list(PROCESSED_DIR.glob("*.csv"))

    asset_norm = normalize_name(asset)

    # Direct normalized matching
    for file in csv_files:

        file_norm = normalize_name(file.stem)

        if asset_norm in file_norm:
            return file

    # Special cases
    aliases = {
        "RELIANCE": ["reliance", "reliancens"],
        "GACM Technologies": ["gacm", "gacmtechnologies"],
        "ETERNAL": ["eternal"],
        "IRFC": ["irfc"],
        "RVNL": ["rvnl"],
        "RailTel": ["railtel"],
        "Torrent Power": ["torrentpower", "torrent"],
        "NIFTY 50": ["nifty50", "nsei"],
        "BANK NIFTY": ["banknifty", "nsebank"],
        "SENSEX": ["sensex", "bsesn"],
    }

    for alias in aliases.get(asset, []):

        alias_norm = normalize_name(alias)

        for file in csv_files:

            file_norm = normalize_name(file.stem)

            if alias_norm in file_norm:
                return file

    return None


def find_result_file(asset, suffix):
    """
    Locate result CSV generated by backtesting engine.
    Handles spaces/underscores/hyphens.
    """

    files = list(RESULT_DIR.glob("*.csv"))

    asset_norm = normalize_name(asset)
    suffix_norm = normalize_name(suffix)

    candidates = []

    for file in files:

        file_norm = normalize_name(file.name)

        if asset_norm in file_norm and suffix_norm in file_norm:
            candidates.append(file)

    if candidates:
        return candidates[0]

    return None


def find_date_column(df):
    """
    Find date column automatically.
    """

    possible = [
        "Date",
        "date",
        "Datetime",
        "datetime",
        "Timestamp",
        "timestamp",
    ]

    for col in possible:

        if col in df.columns:
            return col

    # Fallback: inspect columns
    for col in df.columns:

        try:

            converted = pd.to_datetime(
                df[col],
                errors="coerce"
            )

            if converted.notna().sum() > len(df) * 0.8:
                return col

        except Exception:
            pass

    return None


def find_equity_column(df):
    """
    Find equity column robustly.
    """

    preferred = [
        "Equity",
        "equity",
        "Equity_Final",
        "equity_final",
        "Portfolio_Value",
        "portfolio_value",
        "Value",
        "value",
    ]

    for col in preferred:

        if col in df.columns:
            return col

    # Fallback: numeric columns
    numeric_cols = df.select_dtypes(
        include=np.number
    ).columns.tolist()

    if numeric_cols:
        return numeric_cols[-1]

    return None


def find_pnl_column(df):
    """
    Find PnL column robustly.
    """

    possible = [
        "PnL",
        "P&L",
        "Profit",
        "ProfitLoss",
        "Profit_Loss",
        "PL",
    ]

    for col in possible:

        if col in df.columns:
            return col

    # Case-insensitive fallback
    for col in df.columns:

        col_norm = normalize_name(col)

        if col_norm in [
            "pnl",
            "profit",
            "profitloss",
            "pl",
        ]:
            return col

    return None


def calculate_metrics(asset, oos_end_date):
    """
    Read generated equity/trade files and calculate OOS metrics.
    """

    equity_file = find_result_file(
        asset,
        "equity_curve"
    )

    trade_file = find_result_file(
        asset,
        "trade_history"
    )

    if equity_file is None:

        print(
            f"WARNING: Equity curve not found for {asset}"
        )

        return None

    equity = pd.read_csv(equity_file)

    if equity.empty:

        print(
            f"WARNING: Equity curve empty for {asset}"
        )

        return None

    equity_col = find_equity_column(equity)

    if equity_col is None:

        print(
            f"WARNING: Equity column not found for {asset}"
        )

        print(
            "Available columns:",
            list(equity.columns)
        )

        return None

    equity_values = pd.to_numeric(
        equity[equity_col],
        errors="coerce"
    ).dropna()

    if len(equity_values) < 2:

        print(
            f"WARNING: Not enough equity data for {asset}"
        )

        return None

    initial_equity = float(
        equity_values.iloc[0]
    )

    final_equity = float(
        equity_values.iloc[-1]
    )

    return_pct = (
        (final_equity / initial_equity) - 1
    ) * 100


    # --------------------------------------------------------
    # Maximum Drawdown
    # --------------------------------------------------------

    running_max = equity_values.cummax()

    drawdown = (
        (equity_values - running_max)
        / running_max
    ) * 100

    max_drawdown = float(
        drawdown.min()
    )


    # --------------------------------------------------------
    # Sharpe Ratio
    # --------------------------------------------------------

    returns = equity_values.pct_change().dropna()

    if (
        len(returns) > 1
        and returns.std() != 0
    ):

        sharpe = (
            returns.mean()
            / returns.std()
        ) * np.sqrt(252)

    else:

        sharpe = 0.0


    # --------------------------------------------------------
    # Trade Metrics
    # --------------------------------------------------------

    total_trades = 0
    win_rate = 0.0
    profit_factor = 0.0

    if trade_file is not None:

        trades = pd.read_csv(
            trade_file
        )

        if not trades.empty:

            pnl_col = find_pnl_column(
                trades
            )

            if pnl_col:

                pnl = pd.to_numeric(
                    trades[pnl_col],
                    errors="coerce"
                ).dropna()

                total_trades = len(pnl)

                if len(pnl) > 0:

                    winning = pnl[pnl > 0]
                    losing = pnl[pnl < 0]

                    win_rate = (
                        len(winning)
                        / len(pnl)
                    ) * 100

                    if len(losing) > 0:

                        profit_factor = (
                            winning.sum()
                            / abs(losing.sum())
                        )

                    elif len(winning) > 0:

                        profit_factor = np.inf


    # --------------------------------------------------------
    # Return result
    # --------------------------------------------------------

    return {
        "Asset": asset,
        "OOS_Start": OOS_START,
        "OOS_End": str(oos_end_date),
        "InitialEquity": initial_equity,
        "FinalEquity": final_equity,
        "ReturnPct": return_pct,
        "SharpeRatio": sharpe,
        "MaxDrawdownPct": max_drawdown,
        "WinRatePct": win_rate,
        "ProfitFactor": profit_factor,
        "TotalTrades": total_trades,
    }


