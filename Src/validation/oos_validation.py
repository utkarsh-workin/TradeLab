results = []

successful_tests = 0
skipped_tests = 0


# ============================================================
# PROCESS EACH ASSET
# ============================================================

for asset in ASSETS:

    print("-" * 70)
    print(f"Testing: {asset}")

    source_file = find_processed_file(
        asset
    )

    # --------------------------------------------------------
    # Dataset not found
    # --------------------------------------------------------

    if source_file is None:

        print(
            f"WARNING: Dataset not found for {asset}"
        )

        skipped_tests += 1

        continue


    # --------------------------------------------------------
    # Read original dataset
    # --------------------------------------------------------

    try:

        df = pd.read_csv(
            source_file
        )

    except Exception as e:

        print(
            f"ERROR reading dataset: {e}"
        )

        skipped_tests += 1

        continue


    # --------------------------------------------------------
    # Date column
    # --------------------------------------------------------

    date_col = find_date_column(
        df
    )

    if date_col is None:

        print(
            f"WARNING: Date column not found for {asset}"
        )

        skipped_tests += 1

        continue


    df[date_col] = pd.to_datetime(
        df[date_col],
        errors="coerce"
    )

    df = df.dropna(
        subset=[date_col]
    )


    # --------------------------------------------------------
    # OOS DATA
    # --------------------------------------------------------

    oos_df = df[
        df[date_col] >= pd.Timestamp(
            OOS_START
        )
    ].copy()


    # --------------------------------------------------------
    # Not enough OOS data
    # --------------------------------------------------------

    if len(oos_df) < 60:

        print(
            f"WARNING: Only {len(oos_df)} OOS rows "
            f"for {asset}. Skipping."
        )

        skipped_tests += 1

        continue


    oos_start_date = oos_df[
        date_col
    ].min().date()

    oos_end_date = oos_df[
        date_col
    ].max().date()


    print(
        f"OOS rows: {len(oos_df)}"
    )

    print(
        f"Date range: "
        f"{oos_start_date} → {oos_end_date}"
    )


    # --------------------------------------------------------
    # Backup original dataset
    # --------------------------------------------------------

    backup_file = (
        TEMP_DIR / source_file.name
    )

    shutil.copy2(
        source_file,
        backup_file
    )


    try:

        # ----------------------------------------------------
        # Replace with OOS-only dataset
        # ----------------------------------------------------

        oos_df.to_csv(
            source_file,
            index=False
        )


        print(
            "Running existing backtesting engine..."
        )


        # ----------------------------------------------------
        # Force UTF-8 on Windows
        # ----------------------------------------------------

        env = dict(
            os.environ
        )

        env["PYTHONIOENCODING"] = "utf-8"
        env["PYTHONUTF8"] = "1"


        # ----------------------------------------------------
        # Run engine
        # ----------------------------------------------------

        process = subprocess.run(
            [
                sys.executable,
                str(ENGINE)
            ],
            cwd=PROJECT_ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env
        )


        # ----------------------------------------------------
        # Engine failed
        # ----------------------------------------------------

        if process.returncode != 0:

            print(
                f"Engine failed for {asset}"
            )

            print(
                process.stderr[-2000:]
            )

            skipped_tests += 1

            continue


        # ----------------------------------------------------
        # Extract results
        # ----------------------------------------------------

        metrics = calculate_metrics(
            asset,
            oos_end_date
        )


        if metrics is not None:

            results.append(
                metrics
            )

            successful_tests += 1


            print(
                f"Return       : "
                f"{metrics['ReturnPct']:.2f}%"
            )

            print(
                f"Sharpe       : "
                f"{metrics['SharpeRatio']:.3f}"
            )

            print(
                f"Max DD       : "
                f"{metrics['MaxDrawdownPct']:.2f}%"
            )

            print(
                f"Win Rate     : "
                f"{metrics['WinRatePct']:.2f}%"
            )

            print(
                f"Profit Factor: "
                f"{metrics['ProfitFactor']:.2f}"
            )

            print(
                f"Trades       : "
                f"{metrics['TotalTrades']}"
            )

            print(
                "Result extracted successfully."
            )

        else:

            print(
                f"WARNING: Could not extract "
                f"results for {asset}"
            )

            skipped_tests += 1


    finally:

        # ----------------------------------------------------
        # ALWAYS RESTORE ORIGINAL DATASET
        # ----------------------------------------------------

        if backup_file.exists():

            shutil.copy2(
                backup_file,
                source_file
            )

            print(
                "Original dataset restored."
            )


